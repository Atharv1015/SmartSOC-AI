"""
SmartSOC Command Generator v1

Generates a structured response-command proposal for the
autonomous-agent prototype.

Current version:
    - Deterministic command generation
    - Structured command proposal
    - No direct execution
    - No LLM/API dependency

The generated proposal must be passed to the execution layer
by the autonomous agent. This module itself never executes
commands.
"""

from __future__ import annotations

from typing import Dict, Any


class CommandGenerator:
    """Generate response-command proposals."""

    MODEL_VERSION = "command-generator-v1"

    def generate(
        self,
        scenario: str,
        context: Dict[str, Any] | None = None,
    ) -> Dict[str, Any]:
        """
        Generate a structured command proposal.

        Parameters
        ----------
        scenario:
            Security-response scenario.

        context:
            Optional event/context information.

        Returns
        -------
        Dict[str, Any]
            Structured command proposal.
        """

        if not isinstance(scenario, str):
            raise TypeError("scenario must be a string")

        normalized = scenario.strip().lower()

        if not normalized:
            raise ValueError("scenario cannot be empty")

        context = context or {}

        if normalized == "identify_execution_context":
            command = [
                "cmd.exe",
                "/c",
                "whoami",
            ]

            objective = (
                "Identify the Windows security context under "
                "which the execution broker is operating."
            )

        elif normalized == "collect_hostname":
            command = [
                "cmd.exe",
                "/c",
                "hostname",
            ]

            objective = (
                "Identify the hostname of the Windows endpoint."
            )

        elif normalized == "collect_os_information":
            command = [
                "cmd.exe",
                "/c",
                "ver",
            ]

            objective = (
                "Collect the Windows operating-system version."
            )

        else:
            return {
                "generator": self.MODEL_VERSION,
                "status": "NO_PROPOSAL",
                "scenario": scenario,
                "objective": None,
                "command": None,
                "context": context,
                "reason": (
                    "No command proposal is available for "
                    "the supplied scenario."
                ),
            }

        return {
            "generator": self.MODEL_VERSION,
            "status": "PROPOSED",
            "scenario": scenario,
            "objective": objective,
            "command": command,
            "context": context,
            "reason": (
                "Command generated by the SmartSOC "
                "command-generation layer."
            ),
        }


def main() -> None:
    print("=" * 72)
    print("SmartSOC COMMAND GENERATOR v1")
    print("=" * 72)

    generator = CommandGenerator()

    proposal = generator.generate(
        scenario="identify_execution_context",
        context={
            "source": "autonomous-agent-test",
            "technique": "T1087",
        },
    )

    print()
    print("[PROPOSAL]")
    print("Status    :", proposal["status"])
    print("Generator :", proposal["generator"])
    print("Scenario  :", proposal["scenario"])
    print("Objective :", proposal["objective"])
    print("Command   :", proposal["command"])
    print("Reason    :", proposal["reason"])

    print()
    print("=" * 72)


if __name__ == "__main__":
    main()